CREATE TABLE `blog_posts` (
	`id` int AUTO_INCREMENT NOT NULL,
	`title` varchar(300) NOT NULL,
	`slug` varchar(300) NOT NULL,
	`excerpt` text,
	`content` text NOT NULL,
	`coverImageUrl` text,
	`coverImageAlt` varchar(300),
	`category` varchar(100) DEFAULT 'fotografia',
	`tags` text,
	`metaTitle` varchar(70),
	`metaDescription` varchar(200),
	`canonicalUrl` text,
	`ogImageUrl` text,
	`keywords` text,
	`schemaJson` text,
	`author` varchar(200) DEFAULT 'Camilla Vieira',
	`readingTimeMinutes` int DEFAULT 5,
	`wordCount` int DEFAULT 0,
	`isPublished` boolean DEFAULT false,
	`publishedAt` timestamp,
	`isAutoGenerated` boolean DEFAULT false,
	`agentTrendTopic` text,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `blog_posts_id` PRIMARY KEY(`id`),
	CONSTRAINT `blog_posts_slug_unique` UNIQUE(`slug`)
);
